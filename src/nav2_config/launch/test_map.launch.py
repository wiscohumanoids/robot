"""nav2_config / test_map.launch.py

TEST HARNESS: serves one of the fake obstacle maps on /map and publishes the
identity map -> odom transform, in place of slam_stub (which owns both in the
normal stack). Use it only with slam:=external, otherwise there are two /map
publishers:

    ros2 launch bringup full_stack.launch.py sim:=false navigation:=external slam:=external
    ros2 launch nav2_config test_map.launch.py map:=obstacle_2     # obstacle_1|2|3|zigzag
    ros2 launch nav2_config nav2.launch.py
    ros2 run nav2_config avoidance_test.py --map obstacle_2

Maps are generated by scripts/make_test_maps.py.
"""
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def _setup(context):
    name = LaunchConfiguration('map').perform(context)
    yaml_file = os.path.join(get_package_share_directory('nav2_config'), 'maps', name + '.yaml')
    if not os.path.isfile(yaml_file):
        raise RuntimeError(f"test_map.launch.py: no map '{name}' (looked for {yaml_file})")
    return [
        Node(package='nav2_map_server', executable='map_server', name='map_server',
             output='screen', parameters=[{'yaml_filename': yaml_file, 'use_sim_time': False}]),
        Node(package='nav2_lifecycle_manager', executable='lifecycle_manager',
             name='lifecycle_manager_map', output='screen',
             parameters=[{'autostart': True, 'node_names': ['map_server']}]),
        Node(package='tf2_ros', executable='static_transform_publisher',
             name='test_map_to_odom', output='screen',
             arguments=['--x', '0', '--y', '0', '--z', '0',
                        '--yaw', '0', '--pitch', '0', '--roll', '0',
                        '--frame-id', 'map', '--child-frame-id', 'odom']),
    ]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('map', default_value='obstacle_1',
                              description='Map name in nav2_config/maps: obstacle_1, obstacle_2, obstacle_3, zigzag.'),
        OpaqueFunction(function=_setup),
    ])
