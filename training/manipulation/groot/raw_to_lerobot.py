"""Convert raw manipulation episodes (sim/episode_io.py format) into a
GR00T-flavoured LeRobot v2 dataset.

Raw input: <raw_dir>/episode_XXXXXX.npz + episode_XXXXXX.json (20 Hz)
  npz: ego_rgb (T,H,W,3) uint8, [wrist_left_rgb, wrist_right_rgb], q_left_arm (T,7), q_right_arm (T,7),
       q_waist (T,3), grip_left (T,), grip_right (T,), act_left_arm (T,7), act_right_arm (T,7),
       act_grip_left (T,), act_grip_right (T,), obj_pose (T,7)
  json: instruction, object_category, object_name, success, fps, camera_intrinsics, seed, source
Output (layout matches g1_dex1_config.py):
  meta/{info.json, episodes.jsonl, tasks.jsonl, modality.json}, data/chunk-XXX/episode_XXXXXX.parquet,
  videos/chunk-XXX/observation.images.ego_view/episode_XXXXXX.mp4 (H.264, yuv420p)
  stats.json / relative_stats.json are generated by GR00T itself on the first fine-tune load.
Only successful episodes are kept unless --include-failures.

  python raw_to_lerobot.py --raw ~/hsim_data/manip/v1/raw --out ~/hsim_data/manip/v1/lerobot
Needs numpy, pandas, pyarrow and the ffmpeg binary (all present in the GR00T env on the VM).
"""
import argparse
import json
import shutil
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

CHUNK = 1000
STATE_LAYOUT = [("left_arm", "q_left_arm", 7), ("right_arm", "q_right_arm", 7),
                ("left_gripper", "grip_left", 1), ("right_gripper", "grip_right", 1), ("waist", "q_waist", 3)]
ACTION_LAYOUT = [("left_arm", "act_left_arm", 7), ("right_arm", "act_right_arm", 7),
                 ("left_gripper", "act_grip_left", 1), ("right_gripper", "act_grip_right", 1)]
VIDEOS = [("ego_view", "ego_rgb"), ("wrist_left", "wrist_left_rgb"), ("wrist_right", "wrist_right_rgb")]
JOINT_NAMES_ARM = ["shoulder_pitch", "shoulder_roll", "shoulder_yaw", "elbow", "wrist_roll", "wrist_pitch", "wrist_yaw"]


def concat(ep, layout):
    """Concatenate the layout's fields into one array per step."""
    cols = []
    for _, key, dim in layout:
        x = np.asarray(ep[key], np.float32)
        cols.append(x.reshape(len(x), dim))
    return np.concatenate(cols, 1)


def layout_meta(layout):
    """Start and end index of each field."""
    out, i = {}, 0
    for name, _, dim in layout:
        out[name] = {"start": i, "end": i + dim}
        i += dim
    return out, i


def names(layout):
    """Per-dimension names for the layout."""
    out = []
    for name, _, dim in layout:
        if name.endswith("_arm"):
            out += [f"{name.split('_')[0]}_{j}" for j in JOINT_NAMES_ARM]
        elif name == "waist":
            out += ["waist_yaw", "waist_roll", "waist_pitch"]
        else:
            out += [name]
    return out


def write_video(frames, path, fps):
    """Write frames to an MP4 with ffmpeg."""
    path.parent.mkdir(parents=True, exist_ok=True)
    T, H, W, _ = frames.shape
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
           "-r", str(fps), "-i", "-", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast",
           "-crf", "18", "-g", "10", str(path)]
    subprocess.run(cmd, input=np.ascontiguousarray(frames).tobytes(), check=True)


def main():
    """Convert raw episodes into a GR00T LeRobot v2 dataset."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--include-failures", action="store_true")
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args()
    raw, out = Path(a.raw).expanduser(), Path(a.out).expanduser()
    if out.exists():
        if not a.overwrite:
            raise SystemExit(f"{out} exists (use --overwrite)")
        shutil.rmtree(out)
    files = sorted(raw.glob("episode_*.npz"))
    if not files:
        raise SystemExit(f"no episodes in {raw}")

    tasks, episodes, total, fps, shapes, used_videos = {}, [], 0, None, {}, set()
    skipped = 0
    for f in files:
        meta = json.loads(f.with_suffix(".json").read_text())
        if not meta.get("success", False) and not a.include_failures:
            skipped += 1
            continue
        ep = dict(np.load(f))
        fps = fps or int(meta["fps"])
        assert int(meta["fps"]) == fps, f"{f.name}: fps {meta['fps']} != {fps}"
        idx = len(episodes)
        chunk = idx // CHUNK
        state, action = concat(ep, STATE_LAYOUT), concat(ep, ACTION_LAYOUT)
        T = len(state)
        assert len(action) == T and len(ep["ego_rgb"]) == T, f"{f.name}: length mismatch"
        task = meta["instruction"]
        tidx = tasks.setdefault(task, len(tasks))
        df = pd.DataFrame({
            "observation.state": list(state), "action": list(action),
            "timestamp": (np.arange(T) / fps).astype(np.float32),
            "frame_index": np.arange(T, dtype=np.int64), "episode_index": np.full(T, idx, np.int64),
            "index": np.arange(total, total + T, dtype=np.int64), "task_index": np.full(T, tidx, np.int64),
            "annotation.human.task_description": np.full(T, tidx, np.int64),
            "next.reward": np.zeros(T, np.float32), "next.done": np.arange(T) == T - 1,
        })
        dpath = out / f"data/chunk-{chunk:03d}/episode_{idx:06d}.parquet"
        dpath.parent.mkdir(parents=True, exist_ok=True)
        df.to_parquet(dpath, index=False)
        for vname, key in VIDEOS:
            if key in ep:
                used_videos.add(vname)
                shapes[vname] = ep[key].shape[1:]
                write_video(ep[key], out / f"videos/chunk-{chunk:03d}/observation.images.{vname}/episode_{idx:06d}.mp4", fps)
        episodes.append({"episode_index": idx, "tasks": [task], "length": T})
        total += T

    state_meta, sdim = layout_meta(STATE_LAYOUT)
    action_meta, adim = layout_meta(ACTION_LAYOUT)
    modality = {"state": state_meta, "action": action_meta,
                "video": {v: {"original_key": f"observation.images.{v}"} for v in sorted(used_videos)},
                "annotation": {"human.task_description": {"original_key": "task_index"}}}
    features = {
        "action": {"dtype": "float32", "names": names(ACTION_LAYOUT), "shape": [adim]},
        "observation.state": {"dtype": "float32", "names": names(STATE_LAYOUT), "shape": [sdim]},
        "timestamp": {"dtype": "float32", "shape": [1], "names": None},
        "frame_index": {"dtype": "int64", "shape": [1], "names": None},
        "episode_index": {"dtype": "int64", "shape": [1], "names": None},
        "index": {"dtype": "int64", "shape": [1], "names": None},
        "task_index": {"dtype": "int64", "shape": [1], "names": None},
        "annotation.human.task_description": {"dtype": "int64", "shape": [1], "names": None},
    }
    for v in sorted(used_videos):
        h, w, c = shapes[v]
        features[f"observation.images.{v}"] = {
            "dtype": "video", "shape": [h, w, c], "names": ["height", "width", "channels"],
            "info": {"video.height": h, "video.width": w, "video.codec": "h264", "video.pix_fmt": "yuv420p",
                     "video.is_depth_map": False, "video.fps": fps, "video.channels": c, "has_audio": False}}
    info = {"codebase_version": "v2.1", "robot_type": "unitree_g1_dex1_static", "total_episodes": len(episodes),
            "total_frames": total, "total_tasks": len(tasks), "total_videos": len(episodes) * len(used_videos),
            "total_chunks": (len(episodes) - 1) // CHUNK + 1 if episodes else 0, "chunks_size": CHUNK, "fps": fps,
            "splits": {"train": f"0:{len(episodes)}"},
            "data_path": "data/chunk-{episode_chunk:03d}/episode_{episode_index:06d}.parquet",
            "video_path": "videos/chunk-{episode_chunk:03d}/{video_key}/episode_{episode_index:06d}.mp4",
            "features": features}
    meta = out / "meta"; meta.mkdir(parents=True, exist_ok=True)
    (meta / "info.json").write_text(json.dumps(info, indent=2))
    (meta / "modality.json").write_text(json.dumps(modality, indent=2))
    (meta / "episodes.jsonl").write_text("".join(json.dumps(e) + "\n" for e in episodes))
    (meta / "tasks.jsonl").write_text("".join(json.dumps({"task_index": i, "task": t}) + "\n" for t, i in tasks.items()))
    print(f"wrote {len(episodes)} episodes ({total} frames, {len(tasks)} tasks, videos {sorted(used_videos)}) to {out}; "
          f"skipped {skipped} failed episodes")


if __name__ == "__main__":
    main()
