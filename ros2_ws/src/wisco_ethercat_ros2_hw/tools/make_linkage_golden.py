#!/usr/bin/env python3
"""Write test/data/linkage_parity.json, the golden file for the parallel-joint (ankle, waist) conversion.

The ParallelLinkageController converts joint <-> motor angles in C++ (include/wisco_ethercat_ros2_hw/
parallel_linkage.hpp: closed-form joints -> motors, Newton for motors -> joints); the robot model, the training
actuator and the overload penalty use the Python reference (robots/wisco_v1/linkage.py: a numerical root-find per
crank). This script evaluates the Python reference over each mechanism's joint range and stores joint angles, motor
angles and the Jacobian. test/test_parallel_linkage.cpp asserts the C++ gives the same numbers (motor angles to 1e-9
rad); test/test_linkage_golden.py asserts the Python reference still reproduces the file. Regenerate after changing
linkage.json or either model:

  python3 tools/make_linkage_golden.py
"""

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
LINKAGE = os.path.join(REPO, 'robots', 'wisco_v1', 'linkage.json')
OUT = os.path.join(HERE, '..', 'test', 'data', 'linkage_parity.json')
# joint ranges (rad) from robots/wisco_v1/robot.xml, kept 0.02 rad inside; ankle pitch's lower end is the linkage's
# reachable limit (hardware_observations.md, "Ankle pitch range")
RANGES = {'left_ankle': [(-0.52, 0.76), (-0.24, 0.24)], 'right_ankle': [(-0.52, 0.76), (-0.24, 0.24)],
          'waist': [(-0.50, 0.50), (-0.50, 0.50)]}


def mechanism(name):
    """robots/wisco_v1/linkage.py's Mechanism."""
    sys.path.insert(0, os.path.dirname(LINKAGE))
    from linkage import Mechanism
    return Mechanism(name, LINKAGE)


def make(seed=20261117, n=25):
    """Golden data: per mechanism, the zero pose, the range corners and n random poses."""
    rng = np.random.default_rng(seed)
    out = {'note': 'generated by tools/make_linkage_golden.py; checked by test/test_parallel_linkage.cpp',
           'linkage': os.path.relpath(LINKAGE, REPO), 'seed': seed, 'mechanisms': {}}
    for name, ((p0, p1), (r0, r1)) in RANGES.items():
        m = mechanism(name)
        poses = [(0.0, 0.0), (p0, r0), (p0, r1), (p1, r0), (p1, r1)]
        poses += [(rng.uniform(p0, p1), rng.uniform(r0, r1)) for _ in range(n)]
        cases = []
        for q in poses:
            th = m.motor_angles(q)
            cases.append({'q': [float(v) for v in q], 'motor': th.tolist(), 'jacobian': m.jacobian(q).tolist()})
        out['mechanisms'][name] = {'joints': m.joints, 'cases': cases}
    return out


def main():
    """Write (or with --check, compare against) the golden file."""
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    data = make()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as f:
        json.dump(data, f, indent=1)
    print(f'wrote {a.out}: ' + ', '.join(f"{k} {len(v['cases'])} poses" for k, v in data['mechanisms'].items()))


if __name__ == '__main__':
    main()
